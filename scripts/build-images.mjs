// Responsive image pipeline.
// Reads images/src/*.{jpg,jpeg,png} (the originals Nadia sends, any size) and
// writes AVIF + WebP + JPEG at 480/800/1200/1600 px wide (never upscaled;
// portrait images stop at 1200) into images/, plus:
//   images/manifest.json  - dimensions, widths, dominant colour, tiny LQIP
//   css/placeholders.css  - one `.ph-<name>{background-color:…}` class per image
//                           (a CSS class, not an inline style, so the strict CSP holds)
// and prints a ready-to-paste <picture> snippet for each image.
// images/src/logo-transparent.png is the logo, handled by build-icons.mjs.
// Usage: node scripts/build-images.mjs [--force]
import sharp from "sharp";
import { readdirSync, readFileSync, mkdirSync, statSync, existsSync, writeFileSync } from "node:fs";
import { basename, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

process.chdir(fileURLToPath(new URL("..", import.meta.url)));

const SRC = "images/src", OUT = "images";
const WIDTHS = [480, 800, 1200, 1600];
const PORTRAIT_MAX = 1200;              // portrait photos never need to be wider
const SKIP = new Set(["logo-transparent.png"]);
const FORCE = process.argv.includes("--force");
const formats = {
  avif: (s) => s.avif({ quality: 55, effort: 6 }),
  webp: (s) => s.webp({ quality: 80 }),
  jpg:  (s) => s.jpeg({ quality: 82, mozjpeg: true, progressive: true }),
};

mkdirSync(OUT, { recursive: true });
mkdirSync("css", { recursive: true });
const manifestPath = join(OUT, "manifest.json");
const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : {};
const files = readdirSync(SRC).filter((f) => /\.(jpe?g|png)$/i.test(f) && !SKIP.has(f)).sort();
const slug = (f) => basename(f, extname(f)).toLowerCase().replace(/[^a-z0-9]+/g, "-");

// Forget manifest entries whose source photo has been removed.
const live = new Set(files.map(slug));
for (const n of Object.keys(manifest)) if (!live.has(n)) delete manifest[n];

for (const file of files) {
  const name = slug(file);
  const srcPath = join(SRC, file);
  const srcMtime = statSync(srcPath).mtimeMs;
  const complete = manifest[name]?.widths?.every((w) => Object.keys(formats).every((e) => existsSync(join(OUT, `${name}-${w}.${e}`))));
  if (!FORCE && manifest[name]?.mtime === srcMtime && complete) { console.log(`= ${name} (unchanged)`); continue; }

  const img = sharp(srcPath, { limitInputPixels: false }).rotate(); // honour EXIF orientation
  const meta = await img.metadata();
  // .rotate() may swap width/height for EXIF-rotated photos; read the oriented size.
  const oriented = (meta.orientation || 1) >= 5 ? { w: meta.height, h: meta.width } : { w: meta.width, h: meta.height };
  const portrait = oriented.h > oriented.w;
  const maxW = Math.min(oriented.w, portrait ? PORTRAIT_MAX : 1600);
  const widths = WIDTHS.filter((w) => w <= maxW);
  if (!widths.includes(maxW) && maxW < 1600 && maxW < oriented.w) widths.push(maxW);
  if (widths.length === 0) widths.push(oriented.w);          // tiny source: keep its own size
  const ratio = oriented.h / oriented.w;

  for (const w of widths) {
    for (const [ext, encode] of Object.entries(formats)) {
      await encode(img.clone().resize({ width: w, withoutEnlargement: true })).toFile(join(OUT, `${name}-${w}.${ext}`));
    }
  }

  // Average colour (CSS background while loading; the histogram "dominant" colour is often near-black
  // for indoor photos) + 16px blurred LQIP (kept in the manifest in case it is ever wanted).
  const { channels } = await img.clone().removeAlpha().stats();
  const hex = "#" + channels.slice(0, 3).map((c) => Math.round(c.mean).toString(16).padStart(2, "0")).join("");
  const lqip = `data:image/webp;base64,${(await img.clone().resize(16).blur(1).webp({ quality: 40 }).toBuffer()).toString("base64")}`;

  manifest[name] = { source: file, width: oriented.w, height: oriented.h, ratio: +ratio.toFixed(4), widths, color: hex, lqip, mtime: srcMtime };
  console.log(`✓ ${name}: ${widths.join("/")}px x ${Object.keys(formats).join("/")}, colour ${hex}`);
}
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

// Placeholder colours as classes (keeps CSP style-src 'self': no inline style attributes).
writeFileSync("css/placeholders.css", "/* generated by scripts/build-images.mjs - do not edit */\n" +
  Object.entries(manifest).map(([n, m]) => `.ph-${n}{background-color:${m.color}}`).join("\n") + "\n");

// Sizes written
const kb = (p) => (statSync(p).size / 1024).toFixed(0).padStart(4) + " KB";
for (const [name, m] of Object.entries(manifest)) {
  for (const w of m.widths) console.log(`  ${Object.keys(formats).map((e) => `${kb(join(OUT, `${name}-${w}.${e}`))} ${e}`).join("  ")}   ${name}-${w}`);
}

// Snippets (root-relative URLs; adjust `sizes`, `alt` and loading/fetchpriority to the slot)
for (const [name, m] of Object.entries(manifest)) {
  const set = (ext) => m.widths.map((w) => `/images/${name}-${w}.${ext} ${w}w`).join(", ");
  const largest = Math.max(...m.widths);
  const fallback = m.widths.includes(1200) ? 1200 : largest;
  console.log(`
<!-- ${name} (${largest}x${Math.round(largest * m.ratio)}) -->
<picture>
  <source type="image/avif" srcset="${set("avif")}" sizes="(min-width: 900px) 50vw, 100vw">
  <source type="image/webp" srcset="${set("webp")}" sizes="(min-width: 900px) 50vw, 100vw">
  <img src="/images/${name}-${fallback}.jpg" srcset="${set("jpg")}" sizes="(min-width: 900px) 50vw, 100vw"
       width="${largest}" height="${Math.round(largest * m.ratio)}" alt="" loading="lazy" decoding="async" class="ph-${name}">
</picture>`);
}
